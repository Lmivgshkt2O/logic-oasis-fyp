"""Deterministically build the forum controlled-demonstration JSONL corpus."""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
from hashlib import sha256
import json
import os
from pathlib import Path
import shutil
import tempfile
from typing import Iterable, Mapping

from .schema import RUBRIC_DOCUMENT, ForumScenarioCatalogue, catalogue_document, load_catalogue


DEFAULT_CATALOGUE_PATH = Path(__file__).with_name("forum_verification_catalog_v1.yaml")
REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
DATASET_VERSION = "forum-controlled-demo-dataset-v1"


@dataclass(frozen=True)
class ForumDatasetRow:
    example_id: str
    text: str
    label: str
    language: str
    scenario_family_id: str
    question_family_id: str | None
    mathematics_scenario_family: str
    rubric_version: str
    catalog_version: str
    provenance: str
    evidence_level: str
    catalogue_sha256: str
    rubric_sha256: str
    author_declaration: str
    prompt: str
    mode: str
    expected_correct: bool | None
    expected_relevance: str
    expected_composite: str

    def document(self) -> dict[str, object]:
        return {
            "exampleId": self.example_id,
            "text": self.text,
            "label": self.label,
            "language": self.language,
            "scenarioFamilyId": self.scenario_family_id,
            "questionFamilyId": self.question_family_id,
            "mathematicsScenarioFamily": self.mathematics_scenario_family,
            "rubricVersion": self.rubric_version,
            "catalogVersion": self.catalog_version,
            "trainingDataProvenance": self.provenance,
            "evidenceLevel": self.evidence_level,
            "sourceCatalogueSha256": self.catalogue_sha256,
            "sourceRubricSha256": self.rubric_sha256,
            "scenarioAuthorDeclaration": self.author_declaration,
            "prompt": self.prompt,
            "mode": self.mode,
            "expectedCorrect": self.expected_correct,
            "expectedRelevance": self.expected_relevance,
            "expectedComposite": self.expected_composite,
        }


@dataclass(frozen=True)
class ForumDatasetBuild:
    rows: tuple[ForumDatasetRow, ...]
    manifest: Mapping[str, object]
    catalogue: ForumScenarioCatalogue
    canonical_jsonl: bytes
    catalogue_source: str
    catalogue_path: Path

    def jsonl_bytes(self) -> bytes:
        return self.canonical_jsonl


def canonical_json_bytes(value: object) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def forum_dataset_jsonl_bytes(rows: Iterable[ForumDatasetRow]) -> bytes:
    return b"".join(canonical_json_bytes(row.document()) + b"\n" for row in rows)


def portable_path_identity(path: str | Path) -> str:
    """Return a non-secret logical path suitable for committed provenance."""
    resolved = Path(path).resolve()
    try:
        return resolved.relative_to(REPOSITORY_ROOT).as_posix()
    except ValueError:
        return resolved.name


def publish_files_atomically(
    files: Iterable[tuple[Path, bytes | None]],
    *,
    commit_marker: Path | None = None,
) -> None:
    """Publish one generated file set with rollback on single-process failure.

    ``None`` content removes a stale generated file as part of the same
    rollback boundary. Staging and backups live beside each destination so
    every individual replace remains same-filesystem and atomic.
    """
    requested = list(files)
    destinations = [path for path, _ in requested]
    if len(destinations) != len(set(destinations)):
        raise ValueError("generated publication destinations must be unique")
    if commit_marker is not None:
        matching = [item for item in requested if item[0] == commit_marker]
        if len(matching) != 1 or matching[0][1] is None:
            raise ValueError("publication commit marker must contain generated bytes")
        requested = [item for item in requested if item[0] != commit_marker] + matching

    staging_directories: dict[Path, Path] = {}
    staged_files: dict[Path, Path] = {}
    applied: list[tuple[Path, Path, bool]] = []
    preserve_staging = False
    try:
        for index, (destination, content) in enumerate(requested):
            parent = destination.parent
            parent.mkdir(parents=True, exist_ok=True)
            staging = staging_directories.get(parent)
            if staging is None:
                staging = Path(tempfile.mkdtemp(prefix=".forum-publication-", dir=parent))
                staging_directories[parent] = staging
            if content is not None:
                staged = staging / f"staged-{index}"
                staged.write_bytes(content)
                staged_files[destination] = staged

        for index, (destination, content) in enumerate(requested):
            staging = staging_directories[destination.parent]
            backup = staging / f"backup-{index}"
            existed = destination.exists()
            if existed:
                os.replace(destination, backup)
            try:
                if content is not None:
                    os.replace(staged_files[destination], destination)
            except Exception:
                # Let the common rollback path restore this destination too.
                # If that restoration also fails, it marks the adjacent
                # staging directory for preservation instead of deleting the
                # only remaining backup in ``finally``.
                applied.append((destination, backup, existed))
                raise
            applied.append((destination, backup, existed))
    except Exception:
        for destination, backup, existed in reversed(applied):
            try:
                destination.unlink(missing_ok=True)
                if existed and backup.exists():
                    os.replace(backup, destination)
            except OSError:
                # Preserve the original publication error. Any rollback failure
                # leaves its backup in the adjacent staging directory for repair.
                preserve_staging = True
        raise
    finally:
        if not preserve_staging:
            for staging in staging_directories.values():
                shutil.rmtree(staging, ignore_errors=True)


def build_forum_dataset(catalogue_path: str | Path = DEFAULT_CATALOGUE_PATH) -> ForumDatasetBuild:
    resolved_catalogue_path = Path(catalogue_path).resolve()
    catalogue = load_catalogue(resolved_catalogue_path)
    return build_forum_dataset_from_catalogue(
        catalogue,
        catalogue_source=portable_path_identity(resolved_catalogue_path),
        catalogue_path=resolved_catalogue_path,
    )


def build_forum_dataset_from_catalogue(
    catalogue: ForumScenarioCatalogue,
    *,
    catalogue_source: str,
    catalogue_path: Path,
) -> ForumDatasetBuild:
    if not catalogue_source or Path(catalogue_source).is_absolute() or "\\" in catalogue_source:
        raise ValueError("catalogue source must be a portable logical path")
    catalogue_sha = sha256(canonical_json_bytes(catalogue_document(catalogue))).hexdigest()
    rubric_sha = sha256(canonical_json_bytes(RUBRIC_DOCUMENT)).hexdigest()
    rows = tuple(sorted((
        ForumDatasetRow(
            example_id=example.example_id,
            text=example.text,
            label=example.label,
            language=example.language,
            scenario_family_id=family.scenario_family_id,
            question_family_id=family.question_family_id,
            mathematics_scenario_family=family.mathematics_scenario_family,
            rubric_version=catalogue.rubric_version,
            catalog_version=catalogue.catalog_version,
            provenance=catalogue.training_data_provenance,
            evidence_level=catalogue.evidence_level,
            catalogue_sha256=catalogue_sha,
            rubric_sha256=rubric_sha,
            author_declaration=catalogue.author_declaration,
            prompt=(
                family.prompt_bm if example.language == "ms" else family.prompt
            ),
            mode=family.mode,
            expected_correct=example.expected_correct,
            expected_relevance=example.expected_relevance,
            expected_composite=example.expected_composite,
        )
        for family in catalogue.scenario_families
        for example in family.examples
    ), key=lambda row: (row.scenario_family_id, row.example_id)))
    dataset_bytes = forum_dataset_jsonl_bytes(rows)
    question_groups = sorted({row.question_family_id for row in rows if row.question_family_id})
    manifest: dict[str, object] = {
        "datasetVersion": DATASET_VERSION,
        "catalogVersion": catalogue.catalog_version,
        "rubricVersion": catalogue.rubric_version,
        "rubricSha256": rubric_sha,
        "catalogueSha256": catalogue_sha,
        "datasetSha256": sha256(dataset_bytes).hexdigest(),
        "rowCount": len(rows),
        "scenarioFamilyCount": len({row.scenario_family_id for row in rows}),
        "questionFamilyCount": len(question_groups),
        "classCounts": dict(sorted(Counter(row.label for row in rows).items())),
        "languageCounts": dict(sorted(Counter(row.language for row in rows).items())),
        "correctnessCounts": dict(sorted(
            Counter(
                "correct" if row.expected_correct is True
                else "incorrect" if row.expected_correct is False
                else "not_applicable"
                for row in rows
            ).items(),
        )),
        "relevanceCounts": dict(sorted(
            Counter(row.expected_relevance for row in rows).items(),
        )),
        "compositeCounts": dict(sorted(
            Counter(row.expected_composite for row in rows).items(),
        )),
        "modeCounts": dict(sorted(Counter(row.mode for row in rows).items())),
        "verifiedEligibleCount": sum(
            1 for row in rows if row.expected_composite == "verified"
        ),
        "shouldNotVerifyCount": sum(
            1 for row in rows if row.expected_composite == "should_not_verify"
        ),
        "irrelevantCount": sum(
            1 for row in rows if row.expected_relevance == "irrelevant"
        ),
        "relevantControlCount": sum(
            1 for row in rows if row.expected_relevance == "relevant"
        ),
        "evaluationGroupKey": "scenarioFamilyId",
        "relatedQuestionGroupKey": "questionFamilyId",
        "trainingDataProvenance": catalogue.training_data_provenance,
        "evidenceLevel": catalogue.evidence_level,
        "claimLevel": catalogue.claim_level,
        "releaseScope": catalogue.release_scope,
        "deploymentScope": catalogue.deployment_scope,
        "authorDeclaration": catalogue.author_declaration,
        "containsLearnerIdentity": False,
        "containsCopiedForumText": False,
        "containsAnswerKeys": False,
        "containsLearnerDistributionClaims": False,
    }
    return ForumDatasetBuild(
        rows, manifest, catalogue, dataset_bytes, catalogue_source, catalogue_path,
    )


def validate_forum_dataset_build(build: ForumDatasetBuild) -> ForumDatasetBuild:
    """Rebuild from the authoritative catalogue and reject forged derivatives."""
    expected = build_forum_dataset(build.catalogue_path)
    if (
        build.catalogue != expected.catalogue
        or build.rows != expected.rows
        or dict(build.manifest) != dict(expected.manifest)
        or build.canonical_jsonl != expected.canonical_jsonl
        or build.catalogue_source != expected.catalogue_source
    ):
        raise ValueError("forum dataset build does not derive from its authoritative catalogue")
    return expected


def write_forum_dataset(
    output_directory: str | Path,
    *,
    catalogue_path: str | Path = DEFAULT_CATALOGUE_PATH,
) -> dict[str, Path]:
    build = build_forum_dataset(catalogue_path)
    output = Path(output_directory)
    output.mkdir(parents=True, exist_ok=True)
    dataset = output / "forum_controlled_demo_v1.jsonl"
    manifest = output / "forum_controlled_demo_v1_manifest.json"
    manifest_bytes = (
        json.dumps(build.manifest, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    ).encode("utf-8")
    publish_files_atomically(
        ((dataset, build.jsonl_bytes()), (manifest, manifest_bytes)),
        commit_marker=manifest,
    )
    return {"dataset": dataset, "manifest": manifest}


def verify_generated_dataset(
    catalogue_path: str | Path,
    dataset_path: str | Path,
    manifest_path: str | Path,
) -> None:
    expected = build_forum_dataset(catalogue_path)
    try:
        actual_dataset = Path(dataset_path).read_bytes()
        actual_manifest = json.loads(Path(manifest_path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError("generated dataset or manifest is unavailable") from error
    if actual_dataset != expected.jsonl_bytes() or actual_manifest != expected.manifest:
        raise ValueError("generated dataset does not rebuild from the authoritative catalogue")
